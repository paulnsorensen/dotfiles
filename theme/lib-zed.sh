# shellcheck shell=bash
# Render the currently loaded scheme as a Zed theme file at $1.
write_zed_theme() {
  local out="$1"
  local panel_background elevated_background border border_variant ui_placeholder
  panel_background=$(yq -r '.zed.panel_background // .palette.base01' "$SCHEME_FILE")
  elevated_background=$(yq -r '.zed.elevated_background // .palette.base01' "$SCHEME_FILE")
  border=$(yq -r '.zed.border // .palette.base02' "$SCHEME_FILE")
  border_variant=$(yq -r '.zed.border // .palette.base01' "$SCHEME_FILE")
  ui_placeholder=$(yq -r '.zed.ui_placeholder // .palette.base03' "$SCHEME_FILE")
  local ui_accent ui_accent_fields="" active_line_number
  ui_accent=$(yq -r '.zed.ui_accent // ""' "$SCHEME_FILE")
  active_line_number="$(pal base0A)"
  if [[ -n "$ui_accent" ]]; then
    active_line_number="$ui_accent"
    ui_accent_fields="        \"text.accent\": \"#${ui_accent}\",
        \"icon.accent\": \"#${ui_accent}\",
        \"border.focused\": \"#${ui_accent}\",
        \"panel.focused_border\": \"#${ui_accent}\",
        \"pane.focused_border\": \"#${ui_accent}\",
        \"modified\": \"#${ui_accent}\",
"
  fi

  cat > "$out" <<ZED_THEME
{
  "\$schema": "https://zed.dev/schema/themes/v0.2.0.json",
  "name": "${SCHEME_NAME}",
  "author": "${SCHEME_AUTHOR} (generated by theme/generate.sh from theme/schemes/${ACTIVE}.yaml — DO NOT EDIT)",
  "themes": [
    {
      "name": "${SCHEME_NAME}",
      "appearance": "dark",
      "style": {
        "background": "#$(pal base00)",
        "editor.background": "#$(pal base00)",
        "surface.background": "#${panel_background}",
        "panel.background": "#${panel_background}",
        "elevated_surface.background": "#${elevated_background}",
        "element.hover": "#$(pal base02)",
        "border": "#${border}",
        "border.variant": "#${border_variant}",
        "editor.gutter.background": "#$(pal base00)",
        "text": "#$(pal base05)",
${ui_accent_fields}        "text.muted": "#$(pal base04)",
        "text.disabled": "#${ui_placeholder}",
        "text.placeholder": "#${ui_placeholder}",
        "editor.foreground": "#$(pal base05)",
        "editor.line_number": "#$(pal base03)",
        "editor.active_line_number": "#${active_line_number}",
        "editor.active_line.background": "#$(pal base01)",
        "error": "#$(pal base08)",
        "warning": "#$(pal base0A)",
        "success": "#$(pal base0B)",
        "info": "#$(pal base0C)",
        "terminal.background": "#$(pal base00)",
        "terminal.foreground": "#$(pal base05)",
        "terminal.ansi.black": "#$(pal base01)",
        "terminal.ansi.red": "#$(pal base08)",
        "terminal.ansi.green": "#$(pal base0B)",
        "terminal.ansi.yellow": "#$(pal base0A)",
        "terminal.ansi.blue": "#$(pal base0D)",
        "terminal.ansi.magenta": "#$(pal base0E)",
        "terminal.ansi.cyan": "#$(pal base0C)",
        "terminal.ansi.white": "#$(pal base05)",
        "terminal.ansi.bright_black": "#$(pal base03)",
        "terminal.ansi.bright_red": "#$(pal base12)",
        "terminal.ansi.bright_green": "#$(pal base14)",
        "terminal.ansi.bright_yellow": "#$(pal base09)",
        "terminal.ansi.bright_blue": "#$(pal base16)",
        "terminal.ansi.bright_magenta": "#$(pal base17)",
        "terminal.ansi.bright_cyan": "#$(pal base15)",
        "terminal.ansi.bright_white": "#$(pal base07)",
        "syntax": {
          "comment": { "color": "#$(pal base03)" },
          "string": { "color": "#$(pal base0B)" },
          "keyword": { "color": "#$(pal base0E)" },
          "function": { "color": "#$(pal base0D)" },
          "type": { "color": "#$(pal base0A)" },
          "number": { "color": "#$(pal base09)" },
          "constant": { "color": "#$(pal base09)" },
          "boolean": { "color": "#$(pal base09)" },
          "variable": { "color": "#$(pal base05)" },
          "operator": { "color": "#$(pal base0E)" },
          "punctuation": { "color": "#$(pal base05)" },
          "property": { "color": "#$(pal base0D)" },
          "tag": { "color": "#$(pal base08)" },
          "embedded": { "color": "#$(pal base05)" }
        },
        "players": [
          { "cursor": "#$(pal base0D)", "background": "#$(pal base0D)", "selection": "#$(pal base0D)3d" },
          { "cursor": "#$(pal base0B)", "background": "#$(pal base0B)", "selection": "#$(pal base0B)3d" },
          { "cursor": "#$(pal base0A)", "background": "#$(pal base0A)", "selection": "#$(pal base0A)3d" },
          { "cursor": "#$(pal base0E)", "background": "#$(pal base0E)", "selection": "#$(pal base0E)3d" },
          { "cursor": "#$(pal base0C)", "background": "#$(pal base0C)", "selection": "#$(pal base0C)3d" },
          { "cursor": "#$(pal base08)", "background": "#$(pal base08)", "selection": "#$(pal base08)3d" },
          { "cursor": "#$(pal base09)", "background": "#$(pal base09)", "selection": "#$(pal base09)3d" },
          { "cursor": "#$(pal base17)", "background": "#$(pal base17)", "selection": "#$(pal base17)3d" }
        ]
      }
    }
  ]
}
ZED_THEME
}
